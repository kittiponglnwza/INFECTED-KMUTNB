--[[
    Building40Layout.lua
    ค่าคงที่ผังอาคาร 40 ปี มจพ. (สเกล 2 เท่า) ที่ทุกชั้นใช้ร่วมกัน
    เพื่อให้บันได / ลิฟต์ / ทางเข้าออก อยู่ในตัวอาคารเดียวกันและตรงแนวดิ่งกันทุกชั้น

    แกนพิกัด (มองจากด้านบน):
      +Z = ด้านหน้าตึก (ฝั่งทางเชื่อมยื่นออกไปยังบันไดใหญ่โรงอาหารชั้น 2)
      -Z = ด้านหลังตึก
      +X = ฝั่งขวา (ทางเข้า-ออกรถชั้น 1)
      -X = ฝั่งซ้าย
]]

local Layout = {}

Layout.GROUND_Y = 1.0        -- ผิวพื้นชั้น 1
Layout.FLOOR_HEIGHT = 22.0   -- ความสูงต่อชั้น
Layout.WALL_THICK = 2.0

function Layout.floorY(floorNumber)
    return Layout.GROUND_Y + (floorNumber - 1) * Layout.FLOOR_HEIGHT
end

-- ตัวอาคารหลักเป็นสี่เหลี่ยมผืนผ้าเดียว (300 x 240 studs)
-- ลิฟต์และบันไดอยู่ในตัวอาคารทั้งหมด (ไม่ยื่นออกนอกกรอบ Z = ±120)
Layout.BODY = { halfX = 150, halfZ = 120 }

-- โซนคอร์หน้า/หลัง ภายในตัวอาคาร
-- ขอบนอกชนผนังตึก (Z = ±120), ลึกเข้ามา 36 studs (ถึง Z = ±84)
-- และโซนห้อง/บล็อกหน้า-หลังลึกถึงขอบลานจอดรถ (Z = ±44, รวมลึก 76 studs)
Layout.CORE = {
    bandInnerZ = 44,   -- ขอบติดลานจอดรถชั้น 1 / โถงกลางชั้น 2
    innerZ = 84,       -- ขอบในของปล่องลิฟต์และบันได
    outerZ = 120,      -- ขอบนอกของตึก (หน้าตึก +120 / หลังตึก -120)
    centerZ = 102,     -- กึ่งกลางปล่องลิฟต์และบันได ((84 + 120) / 2)
    depth = 36,        -- ความลึกปล่องลิฟต์และบันได (120 - 84)
    bandDepth = 76,    -- ความลึกแถบห้องหน้า/หลังทั้งหมด (120 - 44)
    sideX = 47,        -- จุดกึ่งกลางคอร์บันได/ลิฟต์ (±X)
    sideWidth = 46,    -- คอร์ข้าง X = 24..70 และ -70..-24
    centerWidth = 48,  -- ทางเข้าออกกลาง X = -24..24
}

-- ทางเชื่อมยื่นออกด้านหน้าตึกเฉพาะชั้น 2 (เชื่อมจากหน้าตึก Z=120 ไปหาบันไดใหญ่หน้าโรงอาหาร)
Layout.FRONT_BRIDGE = {
    width = 48,        -- กว้างเท่าช่องทางเข้าออกกลาง (-24..24)
    startZ = 120,      -- เริ่มจากขอบหน้าตึก
    endZ = 148,        -- ยื่นออกมา 28 studs
    length = 28,
}

--[[
    บันไดในตัวอาคาร (U-shape, ชานพักกลาง)
      entranceDir : ทิศที่ปากบันไดหันไป (+1 = หันไป +X, -1 = หันไป -X)
                    -> หันหน้าเข้าหาลิฟต์ฝั่งตรงข้ามทางเข้าออก
      startSide   : "left" = ช่วงแรกเริ่มขึ้นจากฝั่งซ้ายมือ (เมื่อยืนหน้าปากบันไดมองเข้าไป)
]]
Layout.STAIRS = {
    Front = { name = "FrontStairs", centerX = -47, centerZ =  102, entranceDir =  1, startSide = "left" },
    Rear  = { name = "RearStairs",  centerX =  47, centerZ = -102, entranceDir = -1, startSide = "left" },
}

-- ลิฟต์ในตัวอาคาร (ประตูหันเข้าหาบันได)
Layout.LIFTS = {
    Front = { name = "FrontLifts", centerX =  47, centerZ =  102, doorDir = -1 },
    Rear  = { name = "RearLifts",  centerX = -47, centerZ = -102, doorDir =  1 },
}

return Layout
